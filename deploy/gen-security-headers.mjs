/**
 * Writes the security headers from deploy/security-headers.mjs into apps/{web,console,table}/vercel.json
 * and deploy/nginx/*.headers.conf. Run after changing the policy:  node deploy/gen-security-headers.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { nginxHeaders, vercelHeaders } from './security-headers.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const NOTE = '# Generated by deploy/gen-security-headers.mjs from deploy/security-headers.mjs: do not edit.\n';

/** The expected content of every generated file, by path relative to the repo root. */
export function generated() {
  /** @type {Record<string, string>} */
  const out = {};
  for (const app of /** @type {const} */ (['web', 'console', 'table'])) {
    const p = `apps/${app}/vercel.json`;
    const cur = JSON.parse(readFileSync(join(root, p), 'utf8'));
    out[p] = `${JSON.stringify({ ...cur, headers: vercelHeaders(app) }, null, 2)}\n`;
    out[`deploy/nginx/${app}.headers.conf`] = NOTE + nginxHeaders(app);
    // Only the web app has an /embed route; elsewhere /embed gets the strict headers.
    out[`deploy/nginx/${app}.embed.headers.conf`] = NOTE + nginxHeaders(app, app === 'web');
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(join(root, 'deploy/nginx'), { recursive: true });
  for (const [p, text] of Object.entries(generated())) writeFileSync(join(root, p), text);
  console.log('security headers written');
}
